"""Tests for the BUILT concierge's new-here surface and the build helpers
that produce it. Contract tests read generated output: the tracked plugin
copy (plugin/skills/parallax-concierge/SKILL.md, regenerated by
`build_bundle.py plugin` and kept current by
test_build_bundle.py::test_tracked_plugin_bundle_matches_source) or a freshly
built claude.ai zip. Each test checks something the build does to the text:
the generated new-here block, the concierge filter, the claude.ai rewrites
and their guards, and what each distribution names and ships. Prose the
build copies through from source unchanged is not tested here; conversation
behavior is covered by the live concierge journey evals.

Presence of the "## New here?" heading, presence of both markers, and
absence of the Investor-profile branch are already covered by
test_build_bundle.py::test_concierge_keeps_new_here_block and
::test_concierge_removes_excluded_routes, not repeated here.
"""
