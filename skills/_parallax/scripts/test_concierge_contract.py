# filter_concierge structure.

def test_filter_concierge_raises_on_a_table_left_with_no_body_rows():
    text = ("| If they say… | Run |\n|---|---|\n"
            "| Desk | `/parallax-desk-call-list` |\n\nNext line.\n")
    with pytest.raises(bb.BuildError, match="no body rows"):
        bb.filter_concierge(text, set())


def test_filter_concierge_keeps_a_table_with_a_kept_body_row():
    text = ("| If they say… | Run |\n|---|---|\n"
            "| Quick | `/parallax-should-i-buy` |\n"
            "| Desk | `/parallax-desk-call-list` |\n\nNext line.\n")
    out = bb.filter_concierge(text, {"parallax-should-i-buy"})
    assert out == ("| If they say… | Run |\n|---|---|\n"
                   "| Quick | `/parallax-should-i-buy` |\n\nNext line.\n")


def test_filter_concierge_drops_child_bullets_with_their_dropped_parent():
    text = ("- Desk phrasing → `/parallax-desk-call-list`\n"
            "  - who do I call today\n"
            "  - my whole desk\n"
            "Unrelated line.\n")
    assert bb.filter_concierge(text, set()) == "Unrelated line.\n"


def test_filter_concierge_raises_when_a_dropped_parent_takes_a_shipped_child():
    text = ("- Desk phrasing → `/parallax-desk-call-list`\n"
            "  - single name → `/parallax-should-i-buy`\n")
    with pytest.raises(bb.BuildError, match="in one item"):
        bb.filter_concierge(text, {"parallax-should-i-buy"})


def test_filter_concierge_raises_on_a_label_left_without_routes():
    text = ("- **Shortcut.** Priority order:\n"
            "  - Desk phrasing → `/parallax-desk-call-list`\n"
            "  - Country name → `/parallax-macro-outlook`\n")
    with pytest.raises(bb.BuildError, match="label left without routes"):
        bb.filter_concierge(text, set())


def test_filter_concierge_kept_parent_keeps_its_kept_children():
    text = ("- **Shortcut.** Priority order:\n"
            "  - Single ticker →\n"
            "    `/parallax-should-i-buy`, then nudges\n"
            "  - Desk phrasing → `/parallax-desk-call-list`\n"
            "  - Holdings → `/parallax-portfolio-checkup`\n"
            "- **Next rule** stays.\n")
    out = bb.filter_concierge(text, {"parallax-should-i-buy", "parallax-portfolio-checkup"})
    assert out == ("- **Shortcut.** Priority order:\n"
                   "  - Single ticker →\n"
                   "    `/parallax-should-i-buy`, then nudges\n"
                   "  - Holdings → `/parallax-portfolio-checkup`\n"
                   "- **Next rule** stays.\n")


def test_filter_concierge_mixing_error_says_in_one_item():
    text = "- `/parallax-should-i-buy` or `/parallax-desk-call-list`\n"
    with pytest.raises(bb.BuildError, match="in one item"):
        bb.filter_concierge(text, {"parallax-should-i-buy"})


